import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { Ajv2020 } from 'ajv/dist/2020.js';
import standalone from 'ajv/dist/standalone/index.js';
const standaloneCode = standalone.default;
import { build } from 'esbuild';
import manifest from '../schemas/app-manifest.schema.json' with { type: 'json' };
import rubric from '../schemas/reviewed-rubric.schema.json' with { type: 'json' };

const ajv = new Ajv2020({
  allErrors: true,
  strict: true,
  strictRequired: false,
  code: { source: true, esm: true },
});
ajv.addSchema(manifest, 'manifest');
ajv.addSchema(rubric, 'rubric');
const result = await build({
  stdin: {
    contents: standaloneCode(ajv, {
      manifestValidator: 'manifest',
      reviewedRubricValidator: 'rubric',
    }),
    resolveDir: fileURLToPath(new URL('..', import.meta.url)),
  },
  bundle: true,
  format: 'esm',
  target: 'es2022',
  write: false,
  banner: { js: '// Generated by npm run schemas:generate. Do not edit.' },
});
const output = result.outputFiles[0];
if (!output) throw new Error('Schema validator generation produced no module.');
const target = new URL('../src/generated/schema_validators.mjs', import.meta.url);
if (process.argv.includes('--check')) {
  if ((await readFile(target, 'utf8')) !== output.text)
    throw new Error('Schema validators are stale. Run npm run schemas:generate.');
} else {
  await writeFile(target, output.text);
}
